function humanizeKey(key) {
  if (/TZS$/i.test(key)) {
    const base = key.slice(0, -3);
    const enBase = TRANSLATIONS.en[base];
    const baseLabel = enBase
      ? enBase
      : base
          .replace(/([A-Z])/g, " $1")
          .replace(/^./, (s) => s.toUpperCase())
          .trim();
    return `${baseLabel} (TZS)`;
  }
  return key
    .replace(/([A-Z])/g, " $1")
    .replace(/^./, (s) => s.toUpperCase())
    .trim();
}

export function getCurrentLanguage() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "sw" || stored === "en") return stored;
  } catch {
    /* ignore */
  }
  return "en";
}

export function setCurrentLanguage(lang) {
  const next = lang === "sw" ? "sw" : "en";
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    /* ignore */
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = next;
  }
  if (typeof window !== "undefined") {
    window.dispatchEvent(
      new CustomEvent("languageChanged", { detail: { lang: next } })
    );
  }
  return next;
}

export function getTranslations(_lang = getCurrentLanguage()) {
  // Always expose English source strings in the React tree.
  // Full-page Google Translate (pageTranslate.js) converts the DOM to Swahili
  // so every label is covered — including hardcoded English text.
  const dict = TRANSLATIONS.en;
  return new Proxy(dict, {
    get(target, prop) {
      if (typeof prop !== "string") return target[prop];
      if (prop in target) return target[prop];
      return humanizeKey(prop);
    },
  });
}

